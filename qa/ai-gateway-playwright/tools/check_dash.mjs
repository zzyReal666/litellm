import { chromium } from "playwright-core";
import fs from "node:fs";
const env = Object.fromEntries(fs.readFileSync(".env","utf8").split("\n").filter(l=>l.includes("=")).map(l=>[l.split("=")[0].trim(), l.split("=").slice(1).join("=").trim()]));
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
await page.goto(`${env.AIG_BASE_URL}/ui/login`, { waitUntil: "domcontentloaded" });
await page.locator('input[name="username"]').fill(env.AIG_USER);
await page.locator('input[name="password"]').fill(env.AIG_PASS);
await page.locator('button[type="submit"]').first().click();
await page.waitForURL(/login=success/);
await page.goto(`${env.AIG_BASE_URL}/ui/logs/`, { waitUntil: "networkidle" });
await page.waitForTimeout(3000);
const panel = page.getByRole("tabpanel", { name: "请求日志" });
const headers = (await panel.locator("thead th:visible").allInnerTexts()).map((t) => t.trim());
const rows = panel.locator("tbody tr:visible");
const first = (await rows.first().locator("td").allInnerTexts()).map((t) => t.trim());
const dashColumns = headers.filter((h, i) => first[i] === "-");
console.log("仍为短横线的列:", JSON.stringify(dashColumns));
console.log("团队名称列:", JSON.stringify(first[headers.indexOf("团队名称")]));
console.log("内部用户列:", JSON.stringify(first[headers.indexOf("内部用户")]));
console.log("TTFT列:", JSON.stringify(first[headers.indexOf("TTFT（秒）")] ?? first[headers.indexOf("TTFT")]));
await browser.close();
