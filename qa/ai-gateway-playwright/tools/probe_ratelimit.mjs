import { chromium } from "playwright-core";
import fs from "node:fs";
const env = Object.fromEntries(fs.readFileSync(".env","utf8").split("\n").filter(l=>l.includes("=")).map(l=>[l.split("=")[0].trim(), l.split("=").slice(1).join("=").trim()]));
const BASE = env.AIG_BASE_URL;
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1200 }, ignoreHTTPSErrors: true });
await page.goto(`${BASE}/ui/login`, { waitUntil: "domcontentloaded" });
await page.locator('input[name="username"]').fill(env.AIG_USER);
await page.locator('input[name="password"]').fill(env.AIG_PASS);
await page.locator('button[type="submit"]').first().click();
await page.waitForURL((u) => !u.toString().includes("/login"), { timeout: 30000 });
await page.waitForTimeout(1500);
await page.goto(`${BASE}/ui/users`, { waitUntil: "networkidle" });
await page.waitForTimeout(2200);
const menus = page.getByLabel(/打开用户操作菜单/);
if (await menus.count() > 1) { await menus.nth(1).click(); await page.waitForTimeout(600); }
await page.getByText(/^编辑用户$/).first().click();
await page.waitForTimeout(2200);
const tpm = page.getByRole("spinbutton", { name: /TPM/i }).first();
console.log("tpm count:", await tpm.count(), "value:", await tpm.inputValue().catch(()=>"?"));
await tpm.fill("999999999999999999999999999999");
console.log("after fill value:", await tpm.inputValue().catch(()=>"?"));
await page.getByRole("button", { name: /保存更改/ }).first().click();
await page.waitForTimeout(2000);
const text = await page.evaluate(() => document.body.innerText);
fs.writeFileSync("/tmp/probe_ratelimit.txt", text);
console.log("zh msg:", /请输入非负整数/.test(text), "| en msg:", /Enter a non-negative whole number/.test(text));
console.log("any too big:", /Too big|过大/.test(text));
const idx = text.search(/请输入非负整数|Enter a non-negative|Too big/);
console.log("context:", idx >= 0 ? text.slice(Math.max(0,idx-200), idx+120) : "none");
await browser.close();
