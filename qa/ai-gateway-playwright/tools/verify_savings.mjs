import { chromium } from "playwright-core";
import fs from "node:fs";
const env = Object.fromEntries(fs.readFileSync(".env","utf8").split("\n").filter(l=>l.includes("=")).map(l=>[l.split("=")[0].trim(), l.split("=").slice(1).join("=").trim()]));
const BASE = env.AIG_BASE_URL;
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1200 }, ignoreHTTPSErrors: true });
await page.goto(`${BASE}/ui/login`, { waitUntil: "domcontentloaded" });
await page.locator('input[name="username"]').fill(env.AIG_USER);
await page.locator('input[name="password"]').fill(env.AIG_PASS);
await page.locator('button[type="submit"]').first().click();
await page.waitForURL((u) => !u.toString().includes("/login"), { timeout: 30000 });
await page.waitForTimeout(1500);
await page.goto(`${BASE}/ui/api-keys`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.getByText("bugtest-key", { exact: true }).first().click();
await page.waitForTimeout(2500);
const savingsTab = page.getByRole("tab", { name: "节省", exact: true }).first();
if (await savingsTab.count()) { await savingsTab.click(); await page.waitForTimeout(3000); }
const text = await page.evaluate(() => document.body.innerText);
fs.writeFileSync("/tmp/savings_after.txt", text);
const english = text.match(/Savings|Running total|Compression|Cumulative|Per day|No usage recorded|Prompt Caching|Auto-router/g) ?? [];
const chinese = ["节省", "累计节省", "压缩", "每日", "累计", "提示词缓存", "自动路由"].filter((w) => text.includes(w));
console.log(JSON.stringify({ english_left: english, chinese_found: chinese }, null, 1));
await browser.close();
