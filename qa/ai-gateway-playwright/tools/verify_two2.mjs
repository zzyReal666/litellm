import { chromium } from "playwright-core";
import fs from "node:fs";
const env = Object.fromEntries(fs.readFileSync(".env","utf8").split("\n").filter(l=>l.includes("=")).map(l=>[l.split("=")[0].trim(), l.split("=").slice(1).join("=").trim()]));
const BASE = env.AIG_BASE_URL;
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1200 }, ignoreHTTPSErrors: true });
const out = {};
await page.goto(`${BASE}/ui/login`, { waitUntil: "domcontentloaded" });
await page.locator('input[name="username"]').fill(env.AIG_USER);
await page.locator('input[name="password"]').fill(env.AIG_PASS);
await page.locator('button[type="submit"]').first().click();
await page.waitForURL((u) => !u.toString().includes("/login"), { timeout: 30000 });
await page.waitForTimeout(1200);
// key edit metadata by label
await page.goto(`${BASE}/ui/api-keys`, { waitUntil: "networkidle" });
await page.waitForTimeout(2200);
await page.getByText("bugtest-key", { exact: true }).first().click();
await page.waitForTimeout(2500);
await page.getByRole("tab", { name: /^设置$/ }).first().click();
await page.waitForTimeout(1200);
await page.getByRole("button", { name: /编辑设置/ }).first().click();
await page.waitForTimeout(1800);
const meta = page.getByLabel("元数据").first();
out.meta_found = await meta.count();
if (await meta.count()) await meta.fill("{bad json");
await page.getByRole("button", { name: /保存更改/ }).first().click();
await page.waitForTimeout(2200);
out.key_validation_text = (await page.evaluate(() => document.body.innerText)).match(/元数据必须是合法的 JSON 对象|Metadata must be a valid JSON object/)?.[0] ?? null;
// ask AI
await page.goto(`${BASE}/ui/usage`, { waitUntil: "networkidle" });
await page.waitForTimeout(2200);
await page.getByRole("button", { name: /询问 AI/ }).first().click();
await page.waitForTimeout(1200);
const ta = page.locator("textarea").last();
if (await ta.count()) { await ta.fill("哪个模型花费最多？"); }
await page.getByRole("button", { name: /发送/ }).first().click();
await page.waitForTimeout(15000);
const usageText = await page.evaluate(() => document.body.innerText);
out.ask_ai_mapped = /AI 助手所用模型没有配置 API Key/.test(usageText);
out.ask_ai_english = /The AI model has no credentials configured/.test(usageText);
out.usage_tail = usageText.slice(-600);
fs.writeFileSync("/tmp/verify_two2.json", JSON.stringify(out, null, 1));
console.log(JSON.stringify(out, null, 1).slice(0, 2500));
await browser.close();
