import { chromium } from "playwright-core";
import fs from "node:fs";
const env = Object.fromEntries(fs.readFileSync(".env","utf8").split("\n").filter(l=>l.includes("=")).map(l=>[l.split("=")[0].trim(), l.split("=").slice(1).join("=").trim()]));
const BASE = env.AIG_BASE_URL;
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1100 }, ignoreHTTPSErrors: true });
await page.goto(`${BASE}/ui/login`, { waitUntil: "domcontentloaded" });
await page.locator('input[name="username"]').fill(env.AIG_USER);
await page.locator('input[name="password"]').fill(env.AIG_PASS);
await page.locator('button[type="submit"]').first().click();
await page.waitForURL((u) => !u.toString().includes("/login"), { timeout: 30000 });
await page.waitForTimeout(2500);
const nav = await page.evaluate(() => Array.from(document.querySelectorAll('nav a, aside a, [data-slot="sidebar"] a')).map((a) => (a.innerText || "").trim()).filter(Boolean));
// 打开命令面板
await page.keyboard.press("Control+k");
await page.waitForTimeout(1200);
const palette = await page.evaluate(() => document.body.innerText.slice(0, 2500));
const placeholders = await page.evaluate(() => Array.from(document.querySelectorAll("input")).map((e) => e.getAttribute("placeholder")).filter(Boolean));
fs.writeFileSync("/tmp/nav_palette.json", JSON.stringify({ nav, palette, placeholders }, null, 1));
console.log("nav:", nav.slice(0, 30).join(" | "));
console.log("placeholders:", JSON.stringify(placeholders));
console.log("palette contains English:", JSON.stringify((palette.match(/Home|Model Insights|Lens|Search pages|Actions|Pages|Recent keys|Open|Navigate|Close|All pages/g) ?? [])));
await browser.close();
