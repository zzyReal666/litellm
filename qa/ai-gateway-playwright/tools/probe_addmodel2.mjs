import { chromium } from "playwright-core";
import fs from "node:fs";
const env = Object.fromEntries(fs.readFileSync(".env","utf8").split("\n").filter(l=>l.includes("=")).map(l=>[l.split("=")[0].trim(), l.split("=").slice(1).join("=").trim()]));
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 }, ignoreHTTPSErrors: true });
await page.goto(`${env.AIG_BASE_URL}/ui/login`, { waitUntil: "domcontentloaded" });
await page.locator('input[name="username"]').fill(env.AIG_USER);
await page.locator('input[name="password"]').fill(env.AIG_PASS);
await page.locator('button[type="submit"]').first().click();
await page.waitForURL(/login=success/);
await page.goto(`${env.AIG_BASE_URL}/ui/models-and-endpoints`, { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.getByRole("tab", { name: "添加模型", exact: true }).first().click().catch(async () => { await page.getByText("添加模型", { exact: true }).first().click(); });
await page.waitForTimeout(2000);
const text = await page.evaluate(() => document.body.innerText);
fs.writeFileSync("/tmp/addmodel_form.txt", text);
const inputs = await page.evaluate(() => Array.from(document.querySelectorAll("input,select,textarea,button")).map(e => ({tag:e.tagName, type:e.getAttribute("type"), id:e.id||"", name:e.getAttribute("name")||"", ph:e.getAttribute("placeholder")||"", txt:(e.innerText||"").trim().slice(0,30), aria:e.getAttribute("aria-label")||""})).filter(x => x.tag !== "BUTTON" || x.txt));
fs.writeFileSync("/tmp/addmodel_inputs.json", JSON.stringify(inputs, null, 1));
console.log("fields:", inputs.length);
await page.screenshot({ path: "artifacts/add-model-form.png", fullPage: false });
await browser.close();
